const MAX_STEPS = 4;

export interface LeadConfirmationContext {
  siteName: string;
  /** Origin every relative link and image is resolved against, e.g. "https://growthgrid.studio". */
  siteUrl: string;
  lang: string;
  /** The logo as a hosted raster, sized for the header; null prints the name instead. */
  logo: { src: string; width: number; height: number; alt: string } | null;
  /** The symbol sits before the name ("with-name") or spells it ("logo-only"). */
  logoWithName: boolean;
  /** Absolute URL of the hero picture, or null to leave it out. */
  heroSrc: string | null;
  /** Site settings › Contact: e.g. "We reply to every enquiry within one business day." */
  responseTime: string;
  contactEmail: string;
  phone: string | null;
  bookingUrl: string | null;
  bookingLabel: string;
  socials: { label: string; url: string }[];
  legalName: string;
  locationLabel: string;
  /** Contact page › What happens next. */
  steps: { heading: string; items: { title: string; description: string }[] };
  /** What the visitor picked, kept to the form's own options so the receipt never relays free text. */
  summary: { services: string[]; timeline: string };
  labels: { services: string; timeline: string };
  /** Site settings › Navigation › Legal (privacy, terms). */
  legalLinks: { label: string; href: string }[];
}

/** Absolute URL for a path or URL in content. */
const resolveUrl = (href: string, base: string) => new URL(href, base.endsWith("/") ? base : `${base}/`).href;

/** `path.svg` → `path.png`: the site prefers the SVG twin of a brand file, mail apps can't draw SVG. */
const rasterTwin = (src: string) => src.replace(/\.svg(?=$|[?#])/i, ".png");

/**
 * Everything the receipt shows besides its copy, from the site settings, the
 * contact page and the services on offer. Pure, so a preview can build it too.
 */
export function leadConfirmationContext(
  lead: NewLead,
  settings: Settings,
  page: ContactPage,
  serviceTitles: string[],
): LeadConfirmationContext {
  const { logo } = resolveBrand(settings);
  const image = logo.image;
  const sized =
    image && image.width > 0 && image.height > 0
      ? {
          src: resolveUrl(rasterTwin(image.src), settings.url),
          width: Math.round((image.width / image.height) * LOGO_HEIGHT),
          height: LOGO_HEIGHT,
          alt: image.alt || settings.name,
        }
      : null;
  const offered = new Set(serviceTitles);
  return {
    siteName: settings.name,
    siteUrl: settings.url,
    lang: localeLanguage(settings.locale),
    logo: sized,
    logoWithName: logo.style === "with-name",
    heroSrc: resolveUrl(HERO_IMAGE.path, settings.url),
    responseTime: settings.contact.responseTime,
    contactEmail: settings.contact.email,
    phone: settings.contact.phone,
    bookingUrl: settings.contact.bookingUrl,
    bookingLabel: page.details.bookingLabel,
    socials: settings.socials.map(({ label, url }) => ({ label, url })),
    legalName: settings.legalName,
    locationLabel: settings.location.label,
    steps: { heading: page.steps.heading, items: page.steps.items.slice(0, MAX_STEPS) },
    summary: {
      services: lead.services.filter((service) => offered.has(service)),
      timeline: page.form.timelineOptions.includes(lead.timeline) ? lead.timeline : "",
    },
    labels: { services: page.emails.alert.servicesLabel, timeline: page.emails.alert.timelineLabel },
    legalLinks: settings.navigation.legal.map(({ label, href }) => ({ label, href })),
  };
}

